class MacPasteInjector:
    """:class:`shoutabout.inject.base.Injector` for macOS. Thread-safe."""

    def __init__(
        self,
        cfg: PasteConfig,
        notifier: Notifier | None = None,
        *,
        pasteboard: Pasteboard | None = None,
        poster: KeyPoster | None = None,
        trusted: Callable[[], bool | None] | None = None,
        secure_input: Callable[[], bool] = secure_input_enabled,
        vkey: VKey | None = None,
        timer: Callable[[float, Callable[[], None]], Any] | None = None,
    ) -> None:
        self.cfg = cfg
        self._notifier = notifier
        self._pb = pasteboard
        self._poster = poster or QuartzKeyPoster()
        if trusted is None:
            from shoutabout.mac.permissions import accessibility_trusted as trusted
        self._trusted = trusted
        self._secure = secure_input
        self._vkey = vkey or VKey()
        self._timer = timer or _start_timer
        self._lock = threading.Lock()
        self._pending: list[Any] = []
        self._told_permission = False

    def _board(self) -> Pasteboard:
        if self._pb is None:
            self._pb = CocoaPasteboard()
        return self._pb

    def _markers(self, restoring: bool) -> tuple[str, ...]:
        out: list[str] = [AUTO_GENERATED]
        if restoring:
            out.append(TRANSIENT)
        if self.cfg.exclude_from_history:
            out.append(CONCEALED)
        return tuple(out)

    def paste(self, text: str) -> PasteResult:
        try:
            return self._paste(text)
        except Exception as exc:
            log.exception("paste failed")
            return PasteResult(pasted=False, warning=f"Couldn't paste on the Mac: {exc}")

    def _paste(self, text: str) -> PasteResult:
        if not text:
            return PasteResult(pasted=False, warning=None)
        board = self._board()
        blocked = None
        if self._trusted() is False:
            blocked = ACCESSIBILITY_WARNING
        elif self._secure():
            blocked = SECURE_INPUT_WARNING
        if blocked is not None:
            return self._leave_on_clipboard(board, text, blocked)
        restore = self.cfg.restore_clipboard
        with self._lock:
            saved = None
            if restore:
                try:
                    saved = board.snapshot()
                except Exception:
                    log.warning("couldn't read the clipboard; it won't be restored", exc_info=True)
                    restore = False
            try:
                ours = board.write_text(text, self._markers(restore))
            except Exception:
                log.exception("couldn't put the text on the clipboard")
                return PasteResult(pasted=False, warning=CLIPBOARD_WARNING)
            try:
                self._poster.post_paste(self._vkey.current())
            except Exception:
                log.exception("couldn't post Cmd+V")
                return PasteResult(pasted=False, warning=SEND_FAILED_WARNING)
        if restore and saved is not None:
            self._schedule_restore(board, saved, ours)
        log.debug("pasted %d characters", len(text))
        return PasteResult(pasted=True)

    def _leave_on_clipboard(self, board: Pasteboard, text: str, warning: str) -> PasteResult:
        try:
            board.write_text(text, self._markers(False))
        except Exception:
            log.exception("couldn't put the text on the clipboard")
            return PasteResult(pasted=False, warning=CLIPBOARD_WARNING)
        if warning == ACCESSIBILITY_WARNING and not self._told_permission:
            self._told_permission = True
            if self._notifier is not None:
                try:
                    self._notifier.notify(NO_PASTE_TITLE, NO_PASTE_MESSAGE)
                except Exception:
                    log.exception("notification failed")
        log.info("not pasted: %s", warning)
        return PasteResult(pasted=False, warning=warning)

    def _schedule_restore(self, board: Pasteboard, saved: list, ours: int) -> None:
        def restore() -> None:
            try:
                if board.change_count() != ours:
                    log.debug("clipboard changed since the paste; not restoring it")
                    return
                board.restore(saved, (TRANSIENT,))
            except Exception:
                log.exception("couldn't restore the clipboard")

        handle = self._timer(self.cfg.restore_delay_ms / 1000.0, restore)
        with self._lock:
            self._pending = [t for t in self._pending if _alive(t)] + [handle]

    def wait_idle(self, timeout: float | None = None) -> bool:
        """Wait for scheduled clipboard restores (the hub calls this before exiting)."""
        with self._lock:
            pending = list(self._pending)
        for handle in pending:
            join = getattr(handle, "join", None)
            if callable(join):
                join(timeout)
        return not any(_alive(t) for t in pending)


def _alive(handle: Any) -> bool:
    check = getattr(handle, "is_alive", None)
    return bool(check()) if callable(check) else False


def _start_timer(delay: float, fn: Callable[[], None]) -> threading.Timer:
    timer = threading.Timer(delay, fn)
    timer.name = "clipboard-restore"
    timer.daemon = True
    timer.start()
    return timer
