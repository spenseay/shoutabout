"""Pasting on macOS: the general pasteboard + Cmd+V posted with CGEventPost.

Like the Windows injector:

1. keep a copy of what's on the pasteboard (every item, every type);
2. put the text on it, marked so clipboard managers skip it (the nspasteboard.org markers
   ``org.nspasteboard.TransientType``/``ConcealedType``/``AutoGeneratedType``, which Maccy,
   Alfred, Raycast, Paste and others respect) and kept off Universal Clipboard
   (``NSPasteboardContentsCurrentHostOnly``), so dictations don't appear on your iPhone;
3. post **Cmd+V and nothing else** (a key down and a key up with only the Command flag;
   never Enter or any other key), marked so our own hotkey listener ignores it;
4. after ``restore_delay_ms``, put the old contents back, unless something else changed
   the pasteboard in the meantime (``changeCount``).

When the text can't be pasted it stays on the pasteboard (never restored) and the result
says why: Accessibility isn't allowed (macOS then silently drops posted keys, so we check
first), or a password field has Secure Keyboard Entry on.

The "V" key is looked up in the current keyboard layout (``UCKeyTranslate`` with the
Command modifier, on the main thread, as macOS requires for the Text Input Sources API), so
Dvorak and AZERTY users get Cmd+V too; it falls back to the ANSI V key.
"""

from __future__ import annotations

import ctypes
import logging
import sys
import threading
from collections.abc import Callable
from typing import Any, Protocol

from shoutabout.config import PasteConfig
from shoutabout.inject.base import NO_PASTE_PERMISSION_WARNING, Notifier
from shoutabout.mac import keys
from shoutabout.models import PasteResult

log = logging.getLogger(__name__)

TRANSIENT = "org.nspasteboard.TransientType"
CONCEALED = "org.nspasteboard.ConcealedType"
AUTO_GENERATED = "org.nspasteboard.AutoGeneratedType"
STRING_TYPE = "public.utf8-plain-text"  # NSPasteboardTypeString

# Without Accessibility every dictation is copied instead (the pill: "Copied · ⌘V to
# paste"); the first one of a session also notifies, and the click opens "Allow access".
ACCESSIBILITY_WARNING = NO_PASTE_PERMISSION_WARNING
NO_PASTE_TITLE = "ShoutAbout can't paste yet"
NO_PASTE_MESSAGE = "Your words are copied: press ⌘V. Click to allow pasting."
SECURE_INPUT_WARNING = "A password field has the focus — text is on your clipboard."
CLIPBOARD_WARNING = "Couldn't use the clipboard on the Mac — not pasted."
SEND_FAILED_WARNING = "Couldn't send the paste keystroke — text is on your clipboard."


class Pasteboard(Protocol):
    def change_count(self) -> int: ...
    def snapshot(self) -> list[list[tuple[str, Any]]]: ...
    def write_text(self, text: str, markers: tuple[str, ...]) -> int: ...
    def restore(self, items: list[list[tuple[str, Any]]], markers: tuple[str, ...]) -> int: ...


class CocoaPasteboard:
    """NSPasteboard.generalPasteboard() (thread-safe for these calls)."""

    def __init__(self) -> None:
        from AppKit import NSPasteboard

        self._pb = NSPasteboard.generalPasteboard()

    def change_count(self) -> int:
        return int(self._pb.changeCount())

    def snapshot(self) -> list[list[tuple[str, Any]]]:
        items: list[list[tuple[str, Any]]] = []
        for item in self._pb.pasteboardItems() or []:
            entry = []
            for kind in item.types() or []:
                data = item.dataForType_(kind)
                if data is not None:
                    entry.append((str(kind), data))
            if entry:
                items.append(entry)
        return items

    def _clear(self) -> None:
        prepare = getattr(self._pb, "prepareForNewContentsWithOptions_", None)
        if prepare is not None:
            prepare(1)  # NSPasteboardContentsCurrentHostOnly: no Universal Clipboard
        else:
            self._pb.clearContents()

    def write_text(self, text: str, markers: tuple[str, ...]) -> int:
        from AppKit import NSPasteboardItem
        from Foundation import NSData

        self._clear()
        item = NSPasteboardItem.alloc().init()
        item.setString_forType_(text, STRING_TYPE)
        for marker in markers:
            item.setData_forType_(NSData.data(), marker)
        if not self._pb.writeObjects_([item]):
            raise OSError("the pasteboard refused the text")
        return self.change_count()

    def restore(self, items: list[list[tuple[str, Any]]], markers: tuple[str, ...]) -> int:
        from AppKit import NSPasteboardItem
        from Foundation import NSData

        self._clear()
        objects = []
        for entry in items:
            item = NSPasteboardItem.alloc().init()
            for kind, data in entry:
                item.setData_forType_(data, kind)
            for marker in markers:
                if all(kind != marker for kind, _ in entry):
                    item.setData_forType_(NSData.data(), marker)
            objects.append(item)
        if objects:
            self._pb.writeObjects_(objects)
        return self.change_count()


class KeyPoster(Protocol):
    def post_paste(self, keycode: int) -> None: ...


class QuartzKeyPoster:
    def post_paste(self, keycode: int) -> None:
        import Quartz

        source = Quartz.CGEventSourceCreate(Quartz.kCGEventSourceStateCombinedSessionState)
        flags = keys.FLAG_COMMAND | keys.DEV_LCMD
        events = []
        for down in (True, False):
            event = Quartz.CGEventCreateKeyboardEvent(source, keycode, down)
            if event is None:
                raise OSError("couldn't create the paste keystroke")
            Quartz.CGEventSetFlags(event, flags)
            Quartz.CGEventSetIntegerValueField(
                event, Quartz.kCGEventSourceUserData, keys.OWN_EVENT_MARK
            )
            events.append(event)
        for event in events:
            Quartz.CGEventPost(Quartz.kCGSessionEventTap, event)


# ----------------------------------------------------------------- the V key


def _carbon() -> Any:
    lib = ctypes.CDLL("/System/Library/Frameworks/Carbon.framework/Carbon")
    lib.TISCopyCurrentKeyboardLayoutInputSource.restype = ctypes.c_void_p
    lib.TISGetInputSourceProperty.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
    lib.TISGetInputSourceProperty.restype = ctypes.c_void_p
    lib.LMGetKbdType.restype = ctypes.c_uint8
    lib.UCKeyTranslate.argtypes = [
        ctypes.c_void_p,  # const UCKeyboardLayout *
        ctypes.c_uint16,  # virtualKeyCode
        ctypes.c_uint16,  # keyAction
        ctypes.c_uint32,  # modifierKeyState
        ctypes.c_uint32,  # keyboardType
        ctypes.c_uint32,  # keyTranslateOptions
        ctypes.POINTER(ctypes.c_uint32),  # deadKeyState
        ctypes.c_ulong,  # maxStringLength (UniCharCount)
        ctypes.POINTER(ctypes.c_ulong),  # actualStringLength
        ctypes.POINTER(ctypes.c_uint16),  # unicodeString
    ]
    lib.UCKeyTranslate.restype = ctypes.c_int32
    lib.IsSecureEventInputEnabled.restype = ctypes.c_ubyte
    return lib


def _cf() -> Any:
    lib = ctypes.CDLL("/System/Library/Frameworks/CoreFoundation.framework/CoreFoundation")
    lib.CFDataGetBytePtr.argtypes = [ctypes.c_void_p]
    lib.CFDataGetBytePtr.restype = ctypes.c_void_p
    lib.CFRelease.argtypes = [ctypes.c_void_p]
    return lib


CMD_KEY_STATE = (1 << 8) >> 8  # (cmdKey >> 8) & 0xFF, as UCKeyTranslate wants it
UC_KEY_ACTION_DOWN = 0
UC_NO_DEAD_KEYS = 1  # 1 << kUCKeyTranslateNoDeadKeysBit


def find_keycode(translate: Callable[[int], str | None], char: str = "v") -> int | None:
    """The key code whose character (with Command held) is ``char``; ANSI V first."""
    order = [keys.KC_ANSI_V, *(k for k in range(128) if k != keys.KC_ANSI_V)]
    for code in order:
        out = translate(code)
        if out is not None and out.lower() == char:
            return code
    return None


def layout_v_keycode() -> int | None:
    """Look up "V" in the current keyboard layout. Main thread only (TIS API)."""
    if sys.platform != "darwin":
        return None
    carbon, cf = _carbon(), _cf()
    source = carbon.TISCopyCurrentKeyboardLayoutInputSource()
    if not source:
        return None
    try:
        prop = ctypes.c_void_p.in_dll(carbon, "kTISPropertyUnicodeKeyLayoutData")
        data = carbon.TISGetInputSourceProperty(source, prop)
        if not data:
            return None
        layout = cf.CFDataGetBytePtr(data)
        kbd_type = carbon.LMGetKbdType()

        def translate(code: int) -> str | None:
            dead = ctypes.c_uint32(0)
            length = ctypes.c_ulong(0)
            buf = (ctypes.c_uint16 * 4)()
            status = carbon.UCKeyTranslate(
                layout,
                code,
                UC_KEY_ACTION_DOWN,
                CMD_KEY_STATE,
                kbd_type,
                UC_NO_DEAD_KEYS,
                ctypes.byref(dead),
                4,
                ctypes.byref(length),
                buf,
            )
            if status != 0 or length.value != 1:
                return None
            return chr(buf[0])

        return find_keycode(translate)
    finally:
        cf.CFRelease(source)


def secure_input_enabled() -> bool:
    """True while a password field (or Secure Keyboard Entry) blocks posted keys."""
    if sys.platform != "darwin":
        return False
    try:
        return bool(_carbon().IsSecureEventInputEnabled())
    except Exception:
        log.debug("couldn't read the secure input state", exc_info=True)
        return False


class VKey:
    """The cached key code for V, refreshed on the main thread before each paste."""

    def __init__(self, lookup: Callable[[], int | None] = layout_v_keycode) -> None:
        self._lookup = lookup
        self.code = keys.KC_ANSI_V

    def refresh(self) -> int:
        try:
            code = self._lookup()
        except Exception:
            log.debug("keyboard layout lookup failed", exc_info=True)
            code = None
        if code is not None:
            self.code = code
        return self.code

    def current(self) -> int:
        if sys.platform != "darwin":
            return self.code
        from shoutabout.mac.cocoa import run_on_main

        return int(run_on_main(self.refresh, timeout=0.3, default=self.code))


